from __future__ import unicode_literals
import frappe
from frappe import _
from edit_print_previewer.editable_print import has_format_editor_role


@frappe.whitelist()
def get_editable_print_html(docname, print_format, doctype="Rent Contract"):
    """Return the rendered Print Format HTML for a document.

    Requires the user to have the 'Format Editor' role.
    The HTML is generated by Frappe's own ``get_print`` so that it already
    contains every Jinja-generated dynamic value and all styling from the
    selected Print Format. No database record is modified.
    """
    # Role-based security: only Format Editor can use this feature
    if not has_format_editor_role():
        frappe.throw(
            _("You do not have permission to use Editable Print Preview. "
              "Please contact your administrator to assign the 'Format Editor' role."),
            frappe.PermissionError,
        )

    # 1. Retrieve the requested document.
    doc = frappe.get_doc(doctype, docname)

    # 2. Check the user's read permission.
    if not frappe.has_permission(doctype, "read", doc):
        frappe.throw(
            _("Not permitted to read {0} {1}").format(doctype, docname),
            frappe.PermissionError,
        )

    # 3. Validate that the selected Print Format belongs to the given doctype.
    pf_doc_type = frappe.db.get_value("Print Format", print_format, "doc_type")
    if pf_doc_type != doctype:
        frappe.throw(
            _("Print Format {0} does not belong to {1}").format(print_format, doctype)
        )

    # 4. Ensure the Print Format is enabled.
    disabled = frappe.db.get_value("Print Format", print_format, "disabled")
    if disabled:
        frappe.throw(
            _("Print Format {0} is disabled").format(print_format)
        )

    # 5. Render the Print Format using Frappe.
    html = frappe.get_print(
        doctype,
        docname,
        print_format=print_format,
        as_pdf=False,
    )

    # 6. Return the rendered HTML.
    return html


@frappe.whitelist()
def save_editable_print_html(docname, print_format, doctype, edited_html):
    """Save the edited HTML as a File attachment on the document.

    Requires the 'Format Editor' role.
    """
    from frappe.utils import now

    # Role-based security
    if not has_format_editor_role():
        frappe.throw(
            _("You do not have permission to save Editable Print Preview. "
              "Please contact your administrator to assign the 'Format Editor' role."),
            frappe.PermissionError,
        )

    doc = frappe.get_doc(doctype, docname)

    if not frappe.has_permission(doctype, "write", doc):
        frappe.throw(
            _("Not permitted to write {0} {1}").format(doctype, docname),
            frappe.PermissionError,
        )

    timestamp = now().replace(":", "-").replace(" ", "_")
    file_name = "Editable Preview - {0} - {1}.html".format(docname, timestamp)

    file_doc = frappe.get_doc(
        {
            "doctype": "File",
            "file_name": file_name,
            "attached_to_doctype": doctype,
            "attached_to_name": docname,
            "content": edited_html,
            "is_private": 0,
        }
    )
    file_doc.insert(ignore_permissions=True)

    return {"file_url": file_doc.file_url, "file_name": file_name}


@frappe.whitelist()
def get_saved_editable_html(docname, doctype="Rent Contract"):
    """Return the most recent saved editable HTML attachment for the document.

    Requires the 'Format Editor' role.
    """
    # Role-based security
    if not has_format_editor_role():
        frappe.throw(
            _("You do not have permission to view Editable Print Preview. "
              "Please contact your administrator to assign the 'Format Editor' role."),
            frappe.PermissionError,
        )

    files = frappe.get_all(
        "File",
        filters={
            "attached_to_doctype": doctype,
            "attached_to_name": docname,
        },
        fields=["name", "file_name", "creation"],
        order_by="creation desc",
        limit_page_length=1,
    )

    if not files:
        return None

    file_doc = frappe.get_doc("File", files[0].name)
    content = file_doc.get_content()

    if isinstance(content, bytes):
        content = content.decode("utf-8")

    return {"file_name": file_doc.file_name, "content": content}
